const stage = document.getElementById("roots-stage");
const buttons = [...document.querySelectorAll(".experience-node")];
const detail = document.getElementById("experience-detail");
const detailName = document.getElementById("detail-name");
const detailRole = document.getElementById("detail-role");
const detailList = document.getElementById("detail-list");
const languageButton = document.getElementById("language");
const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)");
const requestedLanguage = new URLSearchParams(location.search).get("lang");
let language = requestedLanguage === "zh" || requestedLanguage === "en" ? requestedLanguage : (localStorage.getItem("arrival-preview-language") === "en" ? "en" : "zh");
let activeId = null;

function fillDetail(id) {
  const record = experiences[id][language];
  detail.scrollTop = 0;
  detailName.textContent = record.name;
  detailRole.textContent = `${record.role}  ·  ${record.period}`;
  detailList.replaceChildren(...record.details.map(text => {
    const item = document.createElement("li");
    item.textContent = text;
    return item;
  }));
  requestAnimationFrame(updateScrollCue);
}

function updateScrollCue() {
  detail.classList.toggle("can-scroll", detail.scrollHeight - detail.clientHeight - detail.scrollTop > 12);
}

function showDetail(id) {
  if (!experiences[id]) return;
  activeId = id;
  stage.dataset.active = id;
  buttons.forEach(button => button.setAttribute("aria-expanded", String(button.dataset.id === id)));
  fillDetail(id);
  detail.removeAttribute("inert");
  detail.classList.add("is-open");
  requestAnimationFrame(updateScrollCue);
}

function closeDetail(returnFocus = false) {
  const former = activeId;
  activeId = null;
  delete stage.dataset.active;
  detail.classList.remove("is-open");
  detail.setAttribute("inert", "");
  buttons.forEach(button => button.setAttribute("aria-expanded", "false"));
  if (returnFocus && former) {
    buttons.find(button => button.dataset.id === former)?.focus({ preventScroll: true });
  }
}

function setLanguage(next) {
  language = next;
  localStorage.setItem("arrival-preview-language", next);
  document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  document.querySelectorAll("[data-copy]").forEach(node => {
    const key = node.dataset.copy === "hint" && matchMedia("(max-width: 700px)").matches ? "hintMobile" : node.dataset.copy;
    node.innerHTML = copy[next][key];
  });
  buttons.forEach(button => {
    const record = experiences[button.dataset.id][next];
    button.querySelector(".organization").textContent = record.name;
    button.querySelector(".role").textContent = record.role;
    button.querySelector(".period").textContent = record.period;
    button.setAttribute("aria-label", next === "en" ? `Explore ${record.name}, ${record.role}` : `查看${record.name}经历：${record.role}`);
  });
  if (activeId) fillDetail(activeId);
  languageButton.setAttribute("aria-pressed", String(next === "en"));
  languageButton.setAttribute("aria-label", next === "en" ? "切换中文" : "Switch to English");
  document.getElementById("node-field").setAttribute("aria-label", next === "en" ? "Six education and work experiences" : "六段学习与实践经历");
  detail.setAttribute("aria-label", next === "en" ? "Experience details" : "经历详情");
  document.getElementById("detail-close").setAttribute("aria-label", copy[next].close);
  document.title = next === "en" ? "Wang Keying · Experience Roots (Preview 04)" : "王柯颖 · 根系经历地图（预览 04）";
}

buttons.forEach(button => {
  const id = button.dataset.id;
  button.addEventListener("click", () => {
    if (activeId === id) closeDetail();
    else showDetail(id);
  });
  button.addEventListener("keydown", event => {
    if ((event.key === "Enter" || event.key === " ") && !event.repeat) {
      event.preventDefault();
      button.click();
    }
  });
  button.addEventListener("keyup", event => {
    if (event.key === " ") event.preventDefault();
  });
});
document.getElementById("detail-close").addEventListener("click", () => closeDetail(true));
detail.addEventListener("scroll", updateScrollCue, { passive: true });
window.addEventListener("resize", updateScrollCue, { passive: true });
document.addEventListener("pointerdown", event => {
  if (activeId && !event.target.closest(".experience-node, .detail")) closeDetail();
});
document.addEventListener("keydown", event => { if (event.key === "Escape" && activeId) closeDetail(true); });
languageButton.addEventListener("click", () => setLanguage(language === "zh" ? "en" : "zh"));
matchMedia("(max-width: 700px)").addEventListener("change", () => setLanguage(language));
setLanguage(language);

if (!reduceMotion.matches) {
  let targetX = 0, targetY = 0, x = 0, y = 0;
  stage.addEventListener("pointermove", event => {
    if (event.pointerType === "touch") return;
    targetX = (event.clientX / innerWidth - .5) * 2;
    targetY = (event.clientY / innerHeight - .5) * 2;
  }, { passive: true });
  stage.addEventListener("pointerleave", () => { targetX = 0; targetY = 0; });
  function frame() {
    x += (targetX - x) * .05;
    y += (targetY - y) * .05;
    stage.style.setProperty("--look-x", `${(x * 8).toFixed(2)}px`);
    stage.style.setProperty("--look-y", `${(y * 5).toFixed(2)}px`);
    requestAnimationFrame(frame);
  }
  frame();
}
